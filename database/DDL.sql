-- Drone Delivery Management System - Database DDL
-- Database Name: DRONEDELIVERY

CREATE DATABASE IF NOT EXISTS DRONEDELIVERY;
USE DRONEDELIVERY;

CREATE TABLE IF NOT EXISTS USERS(
    USER_ID INT PRIMARY KEY AUTO_INCREMENT,
    FIRST_NAME VARCHAR(25) NOT NULL,
    LAST_NAME VARCHAR(25) NOT NULL,
    EMAIL VARCHAR(50) UNIQUE NOT NULL,
    PHONE_NO VARCHAR(10) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    CREATED_AT DATE NOT NULL,
    ROLE ENUM("VENDOR", "CUSTOMER") NOT NULL,

    CHECK(PHONE_NO REGEXP '^[0-9]{10}$'),
    CHECK(EMAIL REGEXP '^[A-Za-z0-9_]+@[A-Za-z]+\\.[A-Za-z]{2,}$')
);

CREATE TABLE IF NOT EXISTS VENDORS(
    VENDOR_ID INT PRIMARY KEY,
    VENDOR_NAME VARCHAR(50) NOT NULL,
    VENDOR_ADDRESS VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS DRONES(
    DRONE_ID INT PRIMARY KEY,
    PAYLOAD_CAP INT NOT NULL,
    CURR_LOCATION VARCHAR(100) NOT NULL,
    PURCHASE_DATE DATE NOT NULL,
    LAST_DELIVERY DATETIME NOT NULL
);

CREATE TABLE IF NOT EXISTS PILOTS(
    PILOT_ID INT PRIMARY KEY AUTO_INCREMENT,
    PILOT_NAME VARCHAR(50) NOT NULL,
    LICENSE_NUMBER VARCHAR(50) UNIQUE NOT NULL,
    PHONE_NO VARCHAR(10) UNIQUE NOT NULL,
    STATUS ENUM('AVAILABLE', 'ON_MISSION', 'OFF_DUTY') NOT NULL DEFAULT 'AVAILABLE',

    CHECK(PHONE_NO REGEXP '^[0-9]{10}$')
);

CREATE TABLE IF NOT EXISTS BATTERIES(
    BATTERY_ID INT PRIMARY KEY,
    DRONE_ID INT NOT NULL,
    CAPACITY INT NOT NULL,
    CYCLES INT NOT NULL,
    STATUS ENUM('GOOD' , 'BAD') NOT NULL DEFAULT "GOOD",

    FOREIGN KEY(DRONE_ID) REFERENCES DRONES(DRONE_ID)
);

CREATE TABLE IF NOT EXISTS MAINTENACE(
    MAINTENANCE_ID INT PRIMARY KEY,
    DRONE_ID INT NOT NULL,
    STATUS ENUM('GOOD' , 'BAD') NOT NULL DEFAULT 'GOOD',
    REPAIR_DATE DATE NOT NULL,
    COST INT NOT NULL,
    REASON VARCHAR(100) NOT NULL DEFAULT 'IN GOOD CONDITION',

    FOREIGN KEY(DRONE_ID) REFERENCES DRONES(DRONE_ID),

    CHECK(COST > 0)
);

CREATE TABLE IF NOT EXISTS CHARGING_SESSIONS(
    BATTERY_ID INT NOT NULL,
    START_TIME DATETIME NOT NULL,
    END_TIME DATETIME DEFAULT NULL,

    PRIMARY KEY(BATTERY_ID, START_TIME),

    FOREIGN KEY(BATTERY_ID) REFERENCES BATTERIES(BATTERY_ID)
);

CREATE TABLE IF NOT EXISTS PACKAGES(
    PACKAGE_ID INT PRIMARY KEY,
    USER_ID INT NOT NULL,
    VENDOR_ID INT NOT NULL,
    PRODUCT_ID INT NOT NULL,
    WEIGHT INT NOT NULL,
    PRIORITY INT NOT NULL,
    STATUS ENUM("AVAILABLE" , "NOT AVAILABLE") NOT NULL DEFAULT "AVAILABLE",

    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID),
    FOREIGN KEY(VENDOR_ID) REFERENCES VENDORS(VENDOR_ID),

    UNIQUE(VENDOR_ID, PRODUCT_ID)
);

CREATE TABLE IF NOT EXISTS ROUTES(
    ROUTE_ID INT NOT NULL PRIMARY KEY,
    SOURCE VARCHAR(25) NOT NULL,
    DESTINATION VARCHAR(25) NOT NULL,
    DISTANCE DECIMAL(10,2) NOT NULL,
    ESTIMATED_TIME INT NOT NULL
);

CREATE TABLE IF NOT EXISTS MISSIONS(
    MISSION_ID INT PRIMARY KEY,
    DRONE_ID INT NOT NULL,
    PILOT_ID INT NOT NULL,
    PACKAGE_ID INT NOT NULL,
    ROUTE_ID INT NOT NULL,
    MISSION_STATUS ENUM("IDLE", "ONGOING", "OVER") NOT NULL,
    START_TIME DATETIME DEFAULT NULL,
    END_TIME DATETIME DEFAULT NULL,

    FOREIGN KEY(DRONE_ID) REFERENCES DRONES(DRONE_ID),
    FOREIGN KEY(PACKAGE_ID) REFERENCES PACKAGES(PACKAGE_ID),
    FOREIGN KEY(PILOT_ID) REFERENCES PILOTS(PILOT_ID),
    FOREIGN KEY(ROUTE_ID) REFERENCES ROUTES(ROUTE_ID)
);

CREATE TABLE IF NOT EXISTS PAYMENTS(
    PAYMENT_ID INT PRIMARY KEY,
    USER_ID INT NOT NULL,
    MISSION_ID INT NOT NULL,
    TIMESTAMP DATETIME NOT NULL,
    MODE ENUM('COD' , 'ONLINE') NOT NULL DEFAULT "ONLINE",
    AMOUNT INT NOT NULL,
    STATUS ENUM("COMPLETED", "PROCESSING", "FAILED") NOT NULL,

    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID),
    FOREIGN KEY(MISSION_ID) REFERENCES MISSIONS(MISSION_ID),

    CHECK(AMOUNT > 0)
);
